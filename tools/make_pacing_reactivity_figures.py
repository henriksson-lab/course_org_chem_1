def save(u,n,name,f):
 import re,textwrap
 from html import escape,unescape
 for i,part in enumerate(f.parts):
  m=re.search(r'<text x="480" y="([\d.]+)".*?>(.*?)</text>',part)
  if m and float(m[1])>=300 and len(unescape(m[2]))>78:
   f.parts[i]='\n'.join(re.sub(r'y="[\d.]+"',f'y="{335+28*j}"',part,count=1).replace(m[2],escape(line)) for j,line in enumerate(textwrap.wrap(unescape(m[2]),width=76)))
 f.save(ROOT/u/'figures'/f'{n:02d}-{name}.svg')
