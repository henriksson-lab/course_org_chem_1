def ring(f,x,y,r=65,nitrogen=False,protonated=False):
 pts=[(x+r*cos(-pi/2+2*pi*i/6),y+r*sin(-pi/2+2*pi*i/6)) for i in range(6)]
 for i,(a,b) in enumerate(zip(pts,pts[1:]+pts[:1])):
  if nitrogen and i==0:a=(a[0]+(b[0]-a[0])*.18,a[1]+(b[1]-a[1])*.18)
  if nitrogen and i==5:b=(b[0]+(a[0]-b[0])*.18,b[1]+(a[1]-b[1])*.18)
  f.line(*a,*b)
 f.circle(x,y,r*.5,color=BLUE,fill='none',width=2)
 if nitrogen:f.text(x,y-r+8,'NH⁺' if protonated else 'N',26)
 return pts

